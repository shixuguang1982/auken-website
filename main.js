  function typeWriter(el, text, speed, done) {
    if (!el) return;
    if (typerTimer) clearTimeout(typerTimer);
    el.textContent = '';
    el.classList.add('typing');
    var i = 0;
    (function step() {
      if (i <= text.length) {
        el.textContent = text.slice(0, i);
        i++;
        typerTimer = setTimeout(step, speed);
      } else {
        el.classList.remove('typing');
        typerTimer = null;
        if (done) done();
      }
    })();
  }

